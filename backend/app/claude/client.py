def execute_claude_tool(
    db: Session,
    tool_name: str,
    tool_input: Dict[str, Any],
    patient_info: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Dispatches tool calls generated by Claude during the agentic loop
    to real database queries and services.
    """
    if tool_name == "find_nearby_facilities":
        radius = tool_input.get("radiusKm", 5.0)
        pathway = tool_input.get("carePathway", "General Consultation")
        facilities = find_nearby_facilities(db, department=pathway, radius_km=radius)
        return {"success": True, "facilities": facilities, "count": len(facilities)}

    elif tool_name == "check_doctor_availability":
        fac_id = tool_input.get("facilityId", "f-agakhan")
        dept_code = tool_input.get("departmentCode", "OPD")
        avail = get_facility_doctor_availability(db, facility_id=fac_id, department_code=dept_code)
        return {"success": True, "availability": avail}

    elif tool_name == "create_appointment_request":
        chief = tool_input.get("chiefConcern", "Medical consultation")
        score = tool_input.get("triageScore", 2)
        urg = tool_input.get("urgency", "Standard")
        fac_id = tool_input.get("facilityId", "f-agakhan")
        slot = tool_input.get("preferredSlot", "Kesho 10:30 AM")
        req_id = f"req-{int(datetime.datetime.now(datetime.timezone.utc).timestamp() * 1000)}-{random.randint(100, 999)}"
        ref_num = f"#{random.randint(20000, 99999)}"

        care_req = CareRequest(
            id=req_id,
            referenceNumber=ref_num,
            patientId=patient_info.get("patientId", "pat-jane-1"),
            facilityId=fac_id,
            chiefConcern=chief,
            symptomDuration="2-3 days",
            secondarySymptoms="[]",
            triageScore=score,
            urgency=urg,
            clinicalSummary=f"Intake: {chief}. Triage: {score}/5.",
            verbatimTranscript=tool_input.get("verbatimTranscript", chief),
            preferredTime=slot,
            status=RequestStatusEnum.RECEIVED,
        )
        db.add(care_req)
        db.commit()
        return {"success": True, "careRequestId": care_req.id, "referenceNumber": ref_num}

    elif tool_name == "propose_appointment":
        req_id = tool_input.get("careRequestId")
        doc_name = tool_input.get("doctorName")
        slot_time = tool_input.get("slotTime")
        care_req = db.query(CareRequest).filter((CareRequest.id == req_id) | (CareRequest.referenceNumber == req_id)).first()
        if care_req:
            care_req.assignedDoctorName = doc_name
            care_req.assignedSlot = slot_time
            care_req.status = RequestStatusEnum.SLOT_PROPOSED
            db.commit()
            return {"success": True, "status": "SLOT_PROPOSED", "doctor": doc_name, "slot": slot_time}
        return {"success": False, "message": "Care request not found"}

    elif tool_name == "confirm_appointment":
        phone = tool_input.get("patientPhone", "+254712345678")
        doc_name = tool_input.get("doctorName", "Dr. Kamau")
        slot_time = tool_input.get("slotTime", "Kesho 10:30 AM")
        token = f"#AC-NBO-{random.randint(1000, 9999)}"
        return {"success": True, "tokenPass": token, "status": "CONFIRMED"}

    elif tool_name == "get_appointment_status":
        req_id = tool_input.get("careRequestId")
        care_req = db.query(CareRequest).filter((CareRequest.id == req_id) | (CareRequest.referenceNumber == req_id)).first()
        if care_req:
            return {"success": True, "status": care_req.status, "tokenPass": care_req.tokenPass}
        return {"success": False, "message": "Care request not found"}

    return {"success": False, "message": f"Unknown tool: {tool_name}"}


def call_anthropic_messages_api(
    messages: List[Dict[str, Any]],
    system_prompt: str = AFYACONNECT_SYSTEM_PROMPT,
    model: str = "claude-3-7-sonnet-20250219",
    api_key: Optional[str] = None,
) -> Optional[Dict[str, Any]]:
    api_key = api_key or os.getenv("ANTHROPIC_API_KEY")
    if not api_key:
        return None

    url = "https://api.anthropic.com/v1/messages"
    payload = {
        "model": model,
        "max_tokens": 1200,
        "system": system_prompt,
        "tools": AFYACONNECT_CLAUDE_TOOLS,
        "messages": messages,
    }

    req = urllib.request.Request(
        url,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "content-type": "application/json",
            "x-api-key": api_key,
            "anthropic-version": "2023-06-01",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            if resp.status == 200:
                return json.loads(resp.read().decode("utf-8"))
    except Exception as e:
        print(f"Live Anthropic Claude API notice: {e}. Utilizing built-in clinical engine.")
        return None


def orchestrate_patient_turn(
    db: Session,
    patient_message: str,
    is_audio: bool = False,
    language_preference: str = "swa_eng",
    patient_info: Optional[Dict[str, Any]] = None,
    history: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    Core conversational orchestration layer.
    Connects patient conversation, tool calling, clinical safety evaluation,
    hospital queue generation, and bilingual feedback cards.
    """
    patient_info = patient_info or {"name": "Jane M.", "phone": "+254712345678", "location": "Westlands, Nairobi"}
    time_now = datetime.datetime.now().strftime("%I:%M %p")

    # 1. Emergency Safety Interception
    safety = evaluate_clinical_safety(patient_message)
    if safety["isEmergency"]:
        return {
            "text": safety["recommendedAction"],
            "responseMessage": safety["recommendedAction"],
            "isEmergency": True,
            "isEmergencyAlert": True,
            "triageScore": 5,
            "urgency": "EMERGENCY",
            "triageLevel": "Triage Level 5 (Emergency)",
            "dialectTag": "Dharura / Emergency Alert",
            "emergencyHotlines": safety.get("emergencyHotlines", []),
            "options": ["🚨 Piga 1199 (Red Cross)", "🏥 Tafuta Hospitali ya Dharura", "🚑 Piga 999 Ambulance"],
            "executedTools": [],
        }

    # 2. Care Pathway & Department
    pathway = determine_care_pathway(patient_message)

    # 3. Location & Nearby Facilities
    nearby = find_nearby_facilities(db, department=pathway["department"], radius_km=5.0)
    primary_facility = nearby[0] if nearby else {
        "id": "f-agakhan",
        "name": "Aga Khan Univ. Hospital",
        "subCounty": "Parklands Sub-County",
        "distanceKm": 1.4,
        "driveTime": "~6 min drive",
        "leadDoctor": "Dr. Wanjiku Kamau",
        "earliestSlot": "Leo 3:30 PM",
    }

    # 4. Availability Check
    avail = get_facility_doctor_availability(db, primary_facility["id"], pathway["departmentCode"])
    lead_doc = avail["availableDoctors"][0]["doctorName"] if avail["availableDoctors"] else primary_facility.get("leadDoctor", "Dr. Wanjiku Kamau")
    earliest_slot = avail["earliestAvailableSlot"]

    # 5. Create Structured Care Request in DB (Case #10482 style)
    req_id = f"req-{int(datetime.datetime.now(datetime.timezone.utc).timestamp() * 1000)}-{random.randint(100, 999)}"
    ref_num = f"#{random.randint(20000, 99999)}"

    care_request = CareRequest(
        id=req_id,
        referenceNumber=ref_num,
        patientId=patient_info.get("patientId", "pat-jane-1"),
        facilityId=primary_facility["id"],
        assignedDoctorName=lead_doc,
        assignedSlot=earliest_slot,
        verbatimTranscript=patient_message,
        chiefConcern=patient_message[:60] if len(patient_message) > 60 else patient_message,
        symptomDuration="2-3 days",
        secondarySymptoms=json.dumps([pathway["department"], "Postural trigger"]),
        triageScore=pathway["triageScore"],
        urgency=UrgencyEnum.URGENT if pathway["urgency"] == "URGENT" else UrgencyEnum.STANDARD,
        clinicalSummary=f"Intake: {patient_message}. Suggested: {pathway['department']}. Triage: {pathway['triageScore']}/5.",
        flags=json.dumps(["Live AI Intake", "Auto-Location Active", "SHA Member"]),
        preferredTime=earliest_slot,
        preferredDate="Kesho, Jumanne 24 Sept",
        status=RequestStatusEnum.RECEIVED,
    )
    db.add(care_request)
    db.flush()

    # Initial 8-step timeline events
    timeline_steps = [
        (1, "CALL / CHAT MADE", "Patient initiated triage conversation via app / audio", time_now, True, False),
        (2, "Request received", "Triage intake logged and pre-screened", time_now, True, False),
        (3, "Hospital received request", f"{primary_facility['name']} intake and triage queue synced", time_now, True, True),
        (4, "Department identified", pathway["department"], "Pending", False, False),
        (5, "Doctor availability checked", f"{lead_doc} calendar check", "Pending", False, False),
        (6, "Time proposed", f"Slot {earliest_slot} pending patient confirmation", "Pending", False, False),
        (7, "Patient confirmed", "Awaiting patient confirmation", "Pending", False, False),
        (8, "APPOINTMENT BOOKED", "Final booking token pending", "Pending", False, False),
    ]
    for step_num, title, desc, ts, comp, act in timeline_steps:
        db.add(CareRequestEvent(
            id=f"evt-{req_id}-{step_num}",
            careRequestId=care_request.id,
            stepNumber=step_num,
            title=title,
            description=desc,
            actor="Hospital Intake Gateway",
            timestampText=ts,
            isCompleted=comp,
            isActive=act,
        ))
    db.commit()

    # 6. Bilingual Response Generation (Live Claude API with Local Clinical Engine Fallback)
    lower = patient_message.lower()
    live_claude_used = False
    api_key = os.getenv("ANTHROPIC_API_KEY")
    if api_key:
        claude_messages = []
        if history:
            for h in history[-4:]:
                role = "user" if h.get("sender") in ["patient", "user"] else "assistant"
                claude_messages.append({"role": role, "content": h.get("text", "")})
        claude_messages.append({"role": "user", "content": patient_message})

        live_res = call_anthropic_messages_api(claude_messages, api_key=api_key)
        if live_res and "content" in live_res:
            for block in live_res["content"]:
                if block.get("type") == "text" and block.get("text"):
                    ai_text = block["text"]
                    live_claude_used = True
                    break

    # Format slot and date labels strictly according to language preference
    is_tomorrow = "kesho" in earliest_slot.lower() or "tomorrow" in earliest_slot.lower()
    clean_slot_time = earliest_slot.replace("Leo ", "").replace("Kesho ", "").replace("Today ", "").replace("Tomorrow ", "")

    if language_preference == "eng":
        dialect_tag = "ENGLISH"
        date_label = "Tomorrow, Tuesday 24 Sept" if is_tomorrow else "Today, Sunday 20 Sept"
        time_label = f"Tomorrow at {clean_slot_time}" if is_tomorrow else f"Today at {clean_slot_time}"
        status_label = "Verified Slot"
    elif language_preference == "swa":
        dialect_tag = "KISWAHILI PEKEE"
        date_label = "Kesho, Jumanne 24 Sept" if is_tomorrow else "Leo, Jumapili 20 Sept"
        time_label = f"Kesho {clean_slot_time}" if is_tomorrow else f"Leo {clean_slot_time}"
        status_label = "Nafasi Imethibitishwa"
    else:
        dialect_tag = "SWA + ENG CODE-SWITCH"
        date_label = "Tomorrow, Tuesday 24 Sept" if is_tomorrow else "Leo, Jumapili 20 Sept"
        time_label = f"Kesho at {clean_slot_time}" if is_tomorrow else f"Leo at {clean_slot_time}"
        status_label = "Verified Slot"

    if not live_claude_used:
        if language_preference == "eng":
            ai_text = (
                f"I understand what you are experiencing regarding your {pathway['department'].lower()}. "
                f"{pathway['explanationEnglish']} I found {len(nearby)} healthcare facilities near you "
                f"in {primary_facility.get('subCounty', 'Nairobi')} with consultation slots available. "
                f"Dr. {lead_doc} at {primary_facility['name']} is available {time_label}. Would you like to book this appointment?"
            )
        elif language_preference == "swa":
            ai_text = (
                f"Nimekuelewa vizuri kuhusu {pathway['department']}. {pathway['explanationSwahili']} "
                f"Nimepata vituo {len(nearby)} vilivyo karibu nawe hapa {primary_facility.get('subCounty', 'Nairobi')} "
                f"vyenye nafasi ya daktari. Daktari {lead_doc} katika {primary_facility['name']} ana nafasi {time_label}. "
                f"Je, ungependa kuthibitisha miadi hii?"
            )
        else:
            # Code-switching: detect if user predominantly typed in English or Swahili
            user_has_swahili = any(sw in lower for sw in ["nimekuwa", "nahisi", "tumbo", "kichwa", "daktari", "kesho", "leo", "homa", "mtoto", "masikio", "jino", "ngozi", "kuona"])
            if not user_has_swahili:
                ai_text = (
                    f"Pole sana, I understand what you are experiencing. {pathway['explanationEnglish']} "
                    f"I found {len(nearby)} nearby healthcare facilities in {primary_facility.get('subCounty', 'Nairobi')}. "
                    f"Dr. {lead_doc} at {primary_facility['name']} has an open slot {time_label}. Would you like to book this consultation?"
                )
            else:
                ai_text = (
                    f"Pole sana, nimekuelewa vizuri: {pathway['explanationSwahili']} "
                    f"Nimepata vituo {len(nearby)} vilivyo karibu hapa Nairobi. "
                    f"Daktari {lead_doc} katika {primary_facility['name']} ana nafasi {time_label}. Je, ungependa kuthibitisha miadi hii?"
                )

    # 7. Feedback Card Data
    feedback_card = {
        "type": "doctor_availability",
        "department": pathway["department"],
        "doctorName": lead_doc,
        "date": date_label,
        "time": time_label,
        "facilityName": primary_facility["name"],
        "requestId": ref_num,
        "statusText": status_label,
    }

    # 8. Nearby Facilities Options Summary for Patient
    nearby_options = [
        {
            "name": f["name"],
            "distance": f"{f['distanceKm']} km",
            "distanceKm": f["distanceKm"],
            "driveTime": f["driveTime"],
            "earliestSlot": f["earliestSlot"],
            "leadDoctor": f["leadDoctor"],
            "facilityId": f["id"],
            "id": f["id"],
            "subCounty": f.get("subCounty", "Parklands Sub-County"),
        }
        for f in nearby[:3]
    ]

    if language_preference == "eng":
        response_options = [
            f"Confirm Slot: {lead_doc} • {time_label}",
            "📍 Check Nearby Facilities",
            "🩺 I need a doctor today",
        ]
    elif language_preference == "swa":
        response_options = [
            f"Thibitisha: {lead_doc} • {time_label}",
            "📍 Tazama Vituo Vilivyo Karibu",
            "🩺 Nahitaji daktari leo",
        ]
    else:
        response_options = [
            f"Confirm Slot: {lead_doc} • {time_label}",
            "📍 Ona Vituo / Other Options",
            "🩺 Nahitaji daktari leo",
        ]

    return {
        "text": ai_text,
        "responseMessage": ai_text,
        "isEmergency": False,
        "isEmergencyAlert": False,
        "triageScore": pathway["triageScore"],
        "urgency": pathway["urgency"],
        "triageLevel": f"Triage Level {pathway['triageScore']}",
        "dialectTag": dialect_tag,
        "feedbackCard": feedback_card,
        "nearbyFacilities": nearby_options,
        "careRequestId": care_request.id,
        "referenceNumber": care_request.referenceNumber,
        "options": response_options,
        "createdCareRequest": {
            "id": care_request.id,
            "referenceNumber": care_request.referenceNumber,
            "chiefConcern": care_request.chiefConcern,
            "urgency": care_request.urgency,
            "status": care_request.status,
            "facilityId": care_request.facilityId,
            "assignedDoctorName": care_request.assignedDoctorName,
            "assignedSlot": care_request.assignedSlot,
        },
        "executedTools": [
            {"toolName": "find_nearby_facilities", "success": True, "count": len(nearby)},
            {"toolName": "check_doctor_availability", "success": True, "doctor": lead_doc, "slot": earliest_slot},
            {"toolName": "create_appointment_request", "success": True, "requestId": ref_num},
        ],
    }
